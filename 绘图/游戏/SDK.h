    // ==================== 运行时可替换偏移表 ====================
    //
    // 动机（来自 TrollSpeed 成品 2 号样本，BackendAdapter.dylib 里的明文 JSON）：
    // 它整个工具里没有一条偏移是编进代码的，全部从 {"actorArray":120,...} 这份表里读，
    // 而且这张表可以从后端下发（yz.php），本地还有 _LocalOffsets 兜底。
    // 结果就是游戏换版本它只要改一行 JSON，不用重新编译签名发版。
    //
    // 我们照这个来：下面的结构体就是那份 JSON 的等价物，字段名尽量对齐它的 key。
    // 默认值 = 我们自己在 S45 实测过的值（与样本表逐条吻合，见下方对照），
    // 运行时若 Documents/offsets.json 存在，就用文件里的值覆盖，改版不用重打包。
    //
    // 与样本 JSON 的对照（左边我们的名字 = 右边的 key = 值）：
    //   坐标节点     = actorArray? 否 —— 我们链的 0x230 在样本里没有对应，属 iOS 特有
    //   坐标组件     = posComponent   = 144 (0x90)
    //   坐标主       = posPrimary     = 96  (0x60)
    //   坐标镜像     = posMirror      = 120 (0x78)
    //   坐标基       = coordBase      = 168 (0xA8)
    //   坐标跳2/3/4  = coordHop2/3/4  = 16 / 0 / 96
    //   坐标X / 坐标Y= posX / posY    = 0 / 8        ← 注意 Y 在 X 后 8 字节，不是 4
    //   血量对象     = hpBase         = 464
    //   血量当前     = hp             = 192
    //   血量上限     = maxHp          = 200
    //   槽距         = entityStride   = 24
    //   英雄ID       = heroId         = 40
    //   回城状态     = recallState    = 360
    //   技能CD       = monsterHp      = 576   ← 样本把它标成 monsterHp，我们的标签可能贴错了，但地址一致
    //   根野怪备     = gameStruct     = 0x133CD510 = 322753808  ← 完全相等
    //   根相机       = matrix         = 0x138A2848 = 327821384  ← 完全相等
    struct 偏移表结构 {
        // 根对象（UnityFramework 模块内静态偏移）
        uint64_t 根世界, 根相机, 根相机备, 根野怪, 根野怪备, 根视距;
        // 实体数组容器：模块+根世界 → +容器中转 → +实体数组(数组) / +数组数量(个数)
        uint64_t 容器中转, 实体数组, 数组数量, 槽距;
        // 坐标链 A（我们实测：#177 走位验证过，3.3~3.9 m/s）
        uint64_t 节点, 节点X, 节点Y;
        // 坐标链 B（样本 coordBase 三跳）
        uint64_t 坐标基, 坐标跳2, 坐标跳3, 坐标跳4;
        // 坐标链 C（样本 posComponent 主/镜像）
        uint64_t 坐标组件, 坐标主, 坐标镜像;
        // 坐标结构内部偏移：x 在 +0，z 在 +8（中间是高度 y，样本 posX=0 / posY=8 实测一致）
        uint64_t 坐标内X, 坐标内Y;
        // 坐标链 D（实体自身静态锚点，仅兜底）
        uint64_t 直接X, 直接Y, 直接Z;
        // 实体字段
        uint64_t 英雄ID, 阵营, 回城标记;
        uint64_t 血量对象, 血量当前, 血量上限;
        uint64_t 技能对象, 技能中转, 技能ID, 技能CD;
        uint64_t 回城对象, 回城状态;
        // 矩阵链
        uint64_t 矩阵跳1, 矩阵跳2, 矩阵跳3, 矩阵字段;
        // 野怪链表
        uint64_t 野怪数组, 野怪列表1, 野怪坐标X, 野怪坐标Y;
        uint64_t 野怪根, 野怪刷新;
    };

